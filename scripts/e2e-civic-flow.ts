import { createClient } from "@supabase/supabase-js";
const url = process.env.SUPABASE_URL!, svc = process.env.SUPABASE_SERVICE_ROLE_KEY!, anon = process.env.SUPABASE_PUBLISHABLE_KEY || process.env.VITE_SUPABASE_PUBLISHABLE_KEY!;
const admin = createClient(url, svc, { auth: { persistSession: false } });
const ok = (n: string, c: unknown, d?: unknown) => console.log(c ? "PASS" : "FAIL", n, c ? "" : JSON.stringify(d));
async function user(email: string) {
  const { data } = await admin.auth.admin.createUser({ email, password: "Test-pass-12345!", email_confirm: true });
  const c = createClient(url, anon, { auth: { persistSession: false } });
  await c.auth.signInWithPassword({ email, password: "Test-pass-12345!" });
  return { id: data.user!.id, c };
}
const cit = await user(`e2e-citizen-${Date.now()}@example.com`);
const wk = await user(`e2e-worker-${Date.now()}@example.com`);
const ins = await cit.c.from("complaints").insert({ user_id: cit.id, title: "E2E pothole", description: "Big pothole near station", category: "broken-road", priority: "high", location: "Station Road, Ratlam", city: "Ratlam", latitude: 23.3316, longitude: 75.0368, submitted_by: "E2E" }).select("id,complaint_id").single();
ok("citizen inserts complaint", !ins.error, ins.error);
const { data: row } = await admin.from("complaints").select("department_id,due_at,ward_id,zone,ai_summary, departments(name), wards(name)").eq("id", ins.data!.id).single();
ok("auto department = Public Works", (row as any)?.departments?.name === "Public Works", row);
ok("deadline set (~72h)", row?.due_at && Math.abs(new Date(row.due_at).getTime() - Date.now() - 72*3600e3) < 120e3, row?.due_at);
ok("ward = Station Road / Zone A", (row as any)?.wards?.name === "Station Road" && row?.zone?.startsWith("Zone A"), row);
ok("fallback summary present", !!row?.ai_summary, row);
const { data: prof } = await admin.from("profiles").select("green_points,complaints_count").eq("user_id", cit.id).single();
ok("points awarded once (10)", prof?.green_points === 10 && prof?.complaints_count === 1, prof);
const near = await cit.c.rpc("find_nearby_duplicates", { _lat: 23.3330, _lng: 75.0370, _category: "broken-road" });
ok("duplicate found within 300 m", near.data?.length === 1, near);
const far = await cit.c.rpc("find_nearby_duplicates", { _lat: 23.3400, _lng: 75.0370, _category: "broken-road" });
ok("no duplicate at ~930 m", far.data?.length === 0, far);
const other = await cit.c.rpc("find_nearby_duplicates", { _lat: 23.3316, _lng: 75.0368, _category: "garbage" });
ok("no duplicate for other category", other.data?.length === 0, other);
const hack = await cit.c.from("complaints").update({ status: "resolved" }).eq("id", ins.data!.id).select();
ok("citizen cannot self-resolve", !!hack.error, hack);
const { data: w } = await admin.from("workers").insert({ name: "E2E Worker" }).select("id").single();
const { data: a } = await admin.from("worker_assignments").insert({ complaint_id: ins.data!.id, worker_id: w!.id }).select("id").single();
await admin.from("workers").update({ user_id: wk.id }).eq("id", w!.id);
const jobs = await wk.c.rpc("my_worker_jobs");
ok("worker sees assigned job", jobs.data?.length === 1, jobs);
const citJobs = await cit.c.rpc("my_worker_jobs");
ok("citizen sees no jobs", citJobs.data?.length === 0, citJobs);
const noPhoto = await wk.c.rpc("worker_update_job", { _assignment_id: a!.id, _status: "completed" });
ok("completion without after-photo rejected", !!noPhoto.error);
const stranger = await cit.c.rpc("worker_update_job", { _assignment_id: a!.id, _status: "completed", _after_photo_url: "x" });
ok("non-assigned user cannot complete", !!stranger.error);
const done = await wk.c.rpc("worker_update_job", { _assignment_id: a!.id, _status: "completed", _after_photo_url: "https://example.com/after.jpg" });
ok("worker completes with photo", !done.error, done.error);
const { data: after } = await cit.c.from("complaints").select("status,before_photo_url,after_photo_url").eq("id", ins.data!.id).single();
ok("complaint resolved with after photo", after?.status === "resolved" && after?.after_photo_url, after);
const tl = await cit.c.from("complaint_timeline").select("status").eq("complaint_id", ins.data!.id);
ok("public timeline entry", tl.data?.some((t) => t.status === "resolved"), tl);
const rate = await cit.c.from("complaint_ratings").insert({ complaint_id: ins.data!.id, user_id: cit.id, rating: 5, feedback: "fixed" });
ok("citizen rates resolution", !rate.error, rate.error);
const pub = createClient(url, anon, { auth: { persistSession: false } });
const pubRead = await pub.from("complaints").select("complaint_id,status,after_photo_url").eq("id", ins.data!.id).single();
ok("public (signed-out) tracking read", pubRead.data?.status === "resolved", pubRead);
const wa = await pub.from("complaints").select("whatsapp_number").limit(1);
ok("private column hidden from public", !!wa.error);
// cleanup
await admin.from("complaints").delete().eq("id", ins.data!.id);
await admin.from("workers").delete().eq("id", w!.id);
await admin.auth.admin.deleteUser(cit.id); await admin.auth.admin.deleteUser(wk.id);
const { data: gone } = await admin.from("profiles").select("id").eq("user_id", cit.id);
ok("account deletion removes profile", gone?.length === 0, gone);
